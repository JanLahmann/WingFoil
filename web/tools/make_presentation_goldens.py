# ---------------------------------------------------------------- the outline stack
#
# The period card's artwork is every session's outline laid on one another, and the one thing
# that makes that a picture rather than a scribble is that they share a **metres** scale: a
# half-hour paddle draws small inside a three-hour reach instead of being stretched to match
# it. Two platforms draw it — `drawTrackStack` in web/js/sharecard.js and `TrackStack` in the
# kit — and neither can be golden-tested on its pixels, so what is pinned here is the
# arithmetic underneath: a set of polylines in metres, a box in layout points, and where every
# vertex lands.
#
# The cases are chosen for the branches, not for realism:
#
#   a week of different lengths   the point of the whole thing — three tracks, one scale
#   up and down one reach        the *other* axis binds, and the fit is centred in the slack
#   one straight leg             dy == 0, so the flat axis imposes no limit and x binds
#   a rider who never moved      no extent on either axis: the degenerate scale, not a crash
#   the wide card's box          the same three tracks, fitted to a landscape slot
#
# Metres, `y` north, in each session's own local frame — which is what both platforms hold:
# `view.x`/`view.y` in the analyzer's document, `TrackThumbnail.Bounds` on the phone.

#: The track slot a portrait card's artwork gets, near enough, in layout points.
STACK_BOX = {"x": 16.0, "y": 64.0, "w": 328.0, "h": 250.0}
#: And a landscape card's, which is wider than it is tall — so the binding axis changes.
STACK_WIDE_BOX = {"x": 16.0, "y": 14.0, "w": 176.0, "h": 334.0}
#: `TRACK_INSET` in web/js/sharecard.js, `ShareCardMapper.inset` on iOS: the stroke's padding
#: plus the mark radius the card's track box reserves. The stack draws no marks and reserves
#: it anyway, so a mapped stack and a plain one come out the same size.
STACK_INSET = 7.2
#: An axis narrower than this has no extent worth fitting by — `TrackStack.flatAxisM`, and the
#: `0.01` in `placerFor`.
STACK_FLAT_AXIS_M = 0.01
#: What a stack with no extent at all is given, rather than a division by zero.
STACK_DEGENERATE_SCALE = 1.0

