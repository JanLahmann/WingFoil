#!/usr/bin/env python3
"""Derive `fixtures/presentation/*.expected.json` from the analysis goldens.

The analysis goldens say what the engine found; these say what a UI is allowed to *draw*
from it. They are the second half of docs/presentation.md's enforcement: both the iOS app
(`PresentationTests.presentationGoldensMatch`) and the web verification
(`web/tools/verify_presentation.py`) assert exactly these numbers, so a marker that
appears on one platform and not on the other is a failing test rather than a bug report a
year later.

    python3 web/tools/make_presentation_goldens.py            # write
    python3 web/tools/make_presentation_goldens.py --check     # exit 1 if stale

Nothing here re-derives a metric: every fact is a *count of what survives an eligibility
rule*, and every rule is written down in docs/presentation.md:

  * turns with `counted == false` are course changes — never an outcome marker, never in a
    tally, never in a trend;
  * a flight end already owned by a turn would double-mark the same swim, and a truncated
    end is a recording that stopped, not an event;
  * pump episodes: only `success` and `failed` are attempts; `recovery`, `in_flight` and
    `unknown` are counted by the engine but never drawn;
  * splash evidence comes from the engine's `submerged` flags and is never re-derived;
  * turn filters are type × ENTRY side, ANDed, over counted turns only;
  * every flight is started by one takeoff and stopped by one end, so the takeoff halves
    and the flight-end buckets each sum to `flightCount`.

Stdlib only, and byte-stable: two runs produce identical files.
"""

