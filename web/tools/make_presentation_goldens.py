def stack_placement(tracks: list, box: dict) -> dict:
    """One scale and one centre for a whole stack, fitted to the union of its extents.

    The reference spelling of `stackPlacer` (web/js/sharecard.js) and `TrackStack.placement`
    (the kit). Uniform in both axes, like every other fit on this card: a track stretched to
    fill two axes is a different-shaped session.
    """
    xs = [p[0] for track in tracks for p in track]
    ys = [p[1] for track in tracks for p in track]
    w = max(box["w"] - STACK_INSET * 2, 1)
    h = max(box["h"] - STACK_INSET * 2, 1)
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    # A perfectly straight leg has zero extent on one axis; that axis then imposes no limit,
    # which is exactly right — the other one takes the fit alone.
    limits = []
    if x1 - x0 > STACK_FLAT_AXIS_M:
        limits.append(w / (x1 - x0))
    if y1 - y0 > STACK_FLAT_AXIS_M:
        limits.append(h / (y1 - y0))
    return {"scale": min(limits) if limits else STACK_DEGENERATE_SCALE,
            "centreX": (x0 + x1) / 2, "centreY": (y0 + y1) / 2,
            "boxCentreX": box["x"] + box["w"] / 2,
            "boxCentreY": box["y"] + box["h"] / 2}


def stack_place(placement: dict, x: float, y: float) -> list[float]:
    """One metre coordinate on the card. `y` is metres north and screen y grows downward, so
    the vertical axis is flipped — north up, the way the map figure draws it."""
    return [round(placement["boxCentreX"] + (x - placement["centreX"]) * placement["scale"], 6),
            round(placement["boxCentreY"] - (y - placement["centreY"]) * placement["scale"], 6)]


def stack_facts() -> dict:
    cases = []
    for case in STACK_CASES:
        placement = stack_placement(case["tracks"], case["box"])
        cases.append({
            "name": case["name"],
            "box": case["box"],
            "tracks": case["tracks"],
            "scale": round(placement["scale"], 9),
            "centreX": round(placement["centreX"], 6),
            "centreY": round(placement["centreY"], 6),
            "placed": [[stack_place(placement, x, y) for x, y in track]
                       for track in case["tracks"]],
        })
    return {"note": STACK_NOTE,
            "rule": {"inset": STACK_INSET, "flatAxisM": STACK_FLAT_AXIS_M,
                     "degenerateScale": STACK_DEGENERATE_SCALE},
            "cases": cases}


def goldens() -> list[Path]:
    return sorted(p for p in GOLDENS.glob(f"*{SUFFIX}"))


def artifacts() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for path in goldens():
        stem = path.name[: -len(SUFFIX)]
        doc = json.loads(path.read_text(encoding="utf-8"))
        out[OUT / f"{stem}{SUFFIX}"] = render(stem, doc)
    out[PERIODS_OUT] = json.dumps(period_facts(), indent=2, ensure_ascii=False) + "\n"
    out[OUTLINES_OUT] = json.dumps(stack_facts(), indent=2, ensure_ascii=False) + "\n"
    return out


def write() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    built = artifacts()
    for path, content in built.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    for orphan in sorted(OUT.glob(f"*{SUFFIX}")):
        if orphan not in built:
            orphan.unlink()
            print(f"  - {orphan.relative_to(REPO).as_posix()} (no analysis golden)")
    print(f"presentation goldens written: {len(built)}")
    for path in sorted(built):
        print(f"  {path.relative_to(REPO).as_posix()}")
    return 0


def check() -> int:
    stale = []
    built = artifacts()
    for path, content in built.items():
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have != content:
            stale.append(path.relative_to(REPO).as_posix())
    for extra in sorted(OUT.glob(f"*{SUFFIX}")):
        if extra not in built:
            stale.append(extra.relative_to(REPO).as_posix())
    if stale:
        print("presentation goldens are STALE — run: "
              "python3 web/tools/make_presentation_goldens.py", file=sys.stderr)
        for name in stale:
            print(f"  differs: {name}", file=sys.stderr)
        return 1
    print(f"presentation goldens are current ({len(built)} fixtures)")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify only; do not write")
    args = ap.parse_args(argv)
    return check() if args.check else write()


if __name__ == "__main__":
    raise SystemExit(main())
