#!/usr/bin/env python3
"""Write docs/copy/assistant-knowledge.md — what "Ask CleanJibe" knows.

The assistant runs on the shared Worker the Fun with Quantum site built (site "cleanjibe",
JanLahmann/Fun-with-Quantum assistant/). The Worker fetches this one file at deploy time and
puts it in the cached system block, so it is built from the same copy every surface prints,
never written by hand: the help topics, the glossary, which feature is in which channel, the
turn coach, the latest release notes, and the voice rules the answers must keep.

    python3 web/tools/make_assistant_knowledge.py            # write
    python3 web/tools/make_assistant_knowledge.py --check    # exit 1 while it is stale
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
COPY = REPO / "docs" / "copy"
OUT = COPY / "assistant-knowledge.md"
RELEASE_NOTES = 6          # the newest entries; older ones only describe what is already in


def _load(name: str) -> dict:
    return json.loads((COPY / name).read_text())


def _channels(chs: list[str]) -> str:
    if not chs or set(chs) == {"release", "beta", "dev"}:
        return ""
    return " [only in: " + ", ".join(chs) + "]"


def voice_rules() -> list[str]:
    text = (REPO / "docs" / "voice.md").read_text()
    m = re.search(r"^## Eleven rules\n(.*?)^## ", text, re.S | re.M)
    return ["## How CleanJibe talks (docs/voice.md)", "", m.group(1).strip(), ""] if m else []


def help_topics() -> list[str]:
    d = _load("help.json")
    out = ["## Help topics (the app's and the website's help, word for word)", ""]
    for sec in d["sections"]:
        out += [f"### {sec['title']}", ""]
        for t in sec["topics"]:
            tag = " [iPhone app only]" if t.get("iphoneOnly") else ""
            out.append(f"#### {t['title']}{_channels(t.get('channels', []))}{tag}")
            if t.get("summary"):
                out.append(t["summary"])
            only = set(t.get("iphoneOnlyBody", []))
            for i, para in enumerate(t.get("body", [])):
                out.append(("[iPhone app only] " if i in only else "") + para)
            for it in t.get("items", []):
                extra = _channels(it.get("channels", []))
                extra += " [iPhone app only]" if it.get("iphoneOnly") else ""
                out.append(f"- {it['term']}{extra}: {it['detail']}")
            if t.get("browser"):
                b = t["browser"]
                out.append("In the browser: " + (" ".join(b) if isinstance(b, list) else str(b)))
            out.append("")
    return out


def glossary() -> list[str]:
    out = ["## What the numbers mean (the glossary)", ""]
    for e in _load("glossary.json")["entries"]:
        also = sorted({x for x in e.get("labels", []) if x.lower() != e["term"].lower()})
        out.append(f"- **{e['term']}**: {e['line']}"
                   + (f" Also printed as: {', '.join(also)}." if also else ""))
    return out + [""]


def channels() -> list[str]:
    c = _load("channels.json")
    out = ["## Which feature is in which channel", "",
           "The iPhone app comes in three channels from one build: release (App Store), "
           "beta (TestFlight, public link testflight.apple.com/join/nygqGGcn) and dev "
           "(a second app for a few hand-picked testers). Beta has everything below; dev "
           "has beta's features and the dev list. The website runs the release analysis.", "",
           "Beta adds:"]
    out += [f"- {r['text']}" for r in c["beta"]]
    out += ["", "Dev adds:"] + [f"- {r['text']}" for r in c["dev"]] + [""]
    return out


def turn_coach() -> list[str]:
    g = _load("app-words.json")["groups"]
    out = ["## The turn coach (what the turn page says, with its tips)", ""]
    for key in ("turns", "turnCoach", "turnCoachTips"):
        for k, v in sorted(g.get(key, {}).items()):
            out.append(f"- {v}")
    return out + [""]


def release_notes() -> list[str]:
    d = _load("whats-new.json")
    out = ["## The newest release notes", ""]
    for e in d["entries"][:RELEASE_NOTES]:
        out.append(f"### {e['version']} ({e['build']}, {e['channel']}, {e['date']}): {e['title']}")
        out += [f"- {line}" for line in e["lines"]] + [""]
    return out


def build() -> str:
    head = [
        "# CleanJibe — what Ask CleanJibe knows",
        "",
        "GENERATED by web/tools/make_assistant_knowledge.py from docs/copy. Do not edit.",
        "",
        "CleanJibe analyses wingfoil sessions: when you were up on the foil, every flight, "
        "and a verdict on every turn (flew through, touchdown or fell in, and clean). It "
        "runs as an iPhone app, in the browser at cleanjibe.org, and as a Garmin watch app "
        "that judges live on the wrist. It is free and non-commercial, built by riders.",
        "",
        "Answering rules: use only facts from this file and from the state you are given. "
        "Never estimate a number yourself. A number marked estimated stays estimated. If "
        "the answer is not here, say you do not know and point to cleanjibe.org/beta/#tell. "
        "Answer in the language of the question. Keep the rider vocabulary below exactly. "
        "A session's speeds come in knots (the fields ending in Kn); say every speed in the "
        "rider's unit from units.speed, converted (1 kn = 1.852 km/h = 1.151 mph = 0.514 m/s), "
        "and never give the knots beside it unless asked. The help's thresholds are written "
        "in km/h; convert those to the rider's unit too. "
        "The state names no place: never say where a session was ridden. The example session "
        "below (Lake Garda) is the app's demo, never the rider's. "
        "There is no Android app; on Android, CleanJibe is the browser app at cleanjibe.org/app. "
        "The vocabulary rule holds in every language: never \"success\", \"successful\" or "
        "\"carried\", nor their translations (German \"erfolgreich\", \"Erfolg\"); say flew "
        "through, clean, dry, touchdown or fell in.",
        "",
    ]
    parts = head + voice_rules() + glossary() + help_topics() + channels() + turn_coach() \
        + release_notes()
    return "\n".join(parts).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/copy/assistant-knowledge.md is stale — run "
                  "python3 web/tools/make_assistant_knowledge.py")
            return 1
        print(f"assistant knowledge is current ({len(text):,} chars)")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)} ({len(text):,} chars, ~{len(text) // 4:,} tokens)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
