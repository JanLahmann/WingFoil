"""Write fixtures/synthetic/jumps.json — the jump detector's cross-implementation fixture.

No recording in the committed corpus holds a real jump (Freddy's sessions stay local), so the
golden files cannot hold the Swift port of `jump.py` to the lab. This fixture does: one wrist
trace at 25 Hz (the rate his fenix 5 Plus logs) with six simulated events and the speed,
flight and turn spans around them, and the lab's verdict on each. The samples are stored
rounded, and the expected answers are computed *from the rounded samples*, so both engines
read the identical input. It also writes garmin/tests/JumpFixtures.mc, the same trace for
the watch's live count (JumpDetector), encoded as a string the watch's test decodes.

    uv run python tools/make_jump_fixture.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from wingfoil_lab import jump as J                                    # noqa: E402

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "fixtures" / "synthetic" / "jumps.json"
WATCH = REPO / "garmin" / "tests" / "JumpFixtures.mc"
RATE = 25.0
NOISE = J.NoiseModel(accel_sigma_g=0.08, accel_rate_hz=RATE, accel_rest_mean_g=1.0,
                     alt_sigma_m=0.19, alt_quantum_m=0.2, alt_rate_hz=1.0)

#: (label, height m, support, speed km/h around it, inside a flight, inside a turn)
EVENTS = [
    ("jump", 1.0, 0.3, 28.0, True, False),
    ("jump", 0.6, 0.45, 30.0, True, False),
    ("chop", 0.05, 0.0, 28.0, True, False),      # under jumpMinAirtime: not even a candidate
    ("too_slow", 0.8, 0.3, 15.0, True, False),
    ("inside_turn", 0.8, 0.3, 28.0, True, True),
    ("off_foil", 0.8, 0.3, 28.0, False, False),
]


def main() -> None:
    rng = np.random.default_rng(1015)
    ts, ms, speed_t, speed_v, flights, turns = [], [], [], [], [], []
    offset = 0.0
    for _label, h, s, kmh, flying, turning in EVENTS:
        sj = J.simulate_jump(h, s, "const", noise=NOISE, rate_hz=RATE, context_s=6.0, rng=rng)
        t = sj.t + offset
        ts.append(t)
        ms.append(sj.mag)
        sec = np.arange(np.ceil(t[0]), t[-1], 1.0)
        speed_t.append(sec)
        speed_v.append(np.full(sec.size, kmh / 3.6))
        if flying:
            flights.append((round(t[0] + 1.0, 2), round(t[-1] - 1.0, 2)))
        if turning:
            turns.append((round(sj.t0 + offset - 2.0, 2), round(sj.t0 + offset + 0.3, 2)))
        offset = float(t[-1]) + 1.0 / RATE

    t = np.round(np.concatenate(ts), 4)
    mag = np.round(np.concatenate(ms), 4)
    st = np.concatenate(speed_t)
    sv = np.round(np.concatenate(speed_v), 4)
    res = J.detect_jumps_from_arrays(t, mag, flight_spans=flights, turn_spans=turns,
                                     speed=(st, sv))
    doc = {
        "note": "Generated by lab/tools/make_jump_fixture.py. Do not edit.",
        "rateHz": RATE,
        "t": t.tolist(), "mag": mag.tolist(),
        "speedT": st.tolist(), "speedMps": sv.tolist(),
        "flightSpans": [list(f) for f in flights], "turnSpans": [list(x) for x in turns],
        "expected": {
            "jumps": [{"startTs": round(j.t_start, 3), "endTs": round(j.t_end, 3),
                       "airtimeS": round(j.height.airtime_s, 4),
                       "heightM": round(j.height.integrated_m, 4),
                       "sigmaM": round(j.height.sigma_m, 4),
                       "takeoffG": round(j.takeoff_g, 4), "impactG": round(j.impact_g, 4)}
                      for j in res.jumps],
            "candidates": [{"startTs": round(c.t_start, 3), "reason": c.reason}
                           for c in res.candidates],
        },
    }
    OUT.write_text(json.dumps(doc, separators=(",", ":")) + "\n")
    write_watch(t, mag, st, sv, flights, turns, len(res.jumps))
    print(f"{OUT.name}: {len(t)} samples, {len(res.jumps)} jumps, "
          f"candidates {[c.reason for c in res.candidates]}")


def _cell(v: int) -> str:
    """33 + v, stepping over 34 and 92 (the quote and the backslash a literal cannot carry)."""
    c = 33 + v
    if c >= 34:
        c += 1
    if c >= 92:
        c += 1
    return chr(c)


def write_watch(t, mag, st, sv, flights, turns, n_jumps: int) -> None:
    """Two characters per 25 Hz sample, |a| in 1 mg steps (base 90, so 0..8.099 g)."""
    step = np.diff(t)
    assert np.allclose(step, 1.0 / RATE, atol=1e-3), "the watch replay assumes a uniform grid"
    codes = np.clip(np.round(mag * 1000.0).astype(int), 0, 90 * 90 - 1)
    enc = "".join(_cell(int(c) // 90) + _cell(int(c) % 90) for c in codes)
    secs = int(np.ceil(t[-1])) + 1
    speed = [0.0] * secs
    for a, v in zip(st, sv):
        speed[int(round(a))] = float(v)
    chunks = [enc[i:i + 96] for i in range(0, len(enc), 96)]
    body = "\n            + ".join(f'"{c}"' for c in chunks)

    def spans(xs):
        return "[" + ", ".join(f"[{round(a * 1000)}, {round(b * 1000)}]" for a, b in xs) + "]"

    WATCH.write_text(f"""import Toybox.Lang;

// GENERATED by lab/tools/make_jump_fixture.py — do not edit by hand.
//
// fixtures/synthetic/jumps.json for the watch: the same 25 Hz wrist trace (two jumps, a chop
// hop, and one event for each of the three context gates), with the 1 Hz context the lab
// read it with. The lab counts {n_jumps}; `jumpCountMatchesTheLab` in WingfoilTests.mc holds
// JumpDetector to that. Every function is (:debug), so none of it reaches a release build.
//
// |a| is two printable characters per sample, 1 mg steps in base 90: cell(v) is 33 + v
// stepping over 34 and 92 (the quote and the backslash), and the test undoes exactly that.
module JumpFixtures {{
    (:debug) function samples() as Number {{ return {len(codes)}; }}
    (:debug) function stepMs() as Number {{ return {round(1000 / RATE)}; }}
    (:debug) function jumps() as Number {{ return {n_jumps}; }}
    (:debug) function flights() as Array<Array<Number> > {{ return {spans(flights)}; }}
    (:debug) function turns() as Array<Array<Number> > {{ return {spans(turns)}; }}
    (:debug) function speedMps() as Array<Float> {{
        return [{", ".join(f"{v:.4f}" for v in speed)}];
    }}
    (:debug) function mag() as String {{
        return {body};
    }}
}}
""")


if __name__ == "__main__":
    main()
